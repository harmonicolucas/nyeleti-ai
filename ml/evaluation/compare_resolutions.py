"""Compare grid resolutions for the harmonization (default 1, 5 and 10 km).

For every cell size that is not the operational one, the script runs the
aggregation, the pair building, a training with the same settings as the
operational model and the evaluation, without registering the model or
touching the application database. It then writes docs/resolution_comparison.md.

Province-day and country-day totals are the same physical quantity at every
resolution, so detection counts and FRP are compared at those levels. HFAI is
left out because its reference values depend on the cell size.

    python -m ml.evaluation.compare_resolutions
    python -m ml.evaluation.compare_resolutions --cell-km 10
    python -m ml.evaluation.compare_resolutions --collect-only
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from datetime import datetime, timezone

from ml import config
from ml.inference.harmonize import active_version


def version_name(cell_km: float) -> str:
    return f"hfai-lgbm-{config.grid_tag(cell_km)}-resolution-test"


def run(module: str, *args: str) -> None:
    result = subprocess.run([sys.executable, "-m", module, *args], cwd=config.ROOT)
    if result.returncode != 0:
        sys.exit(f"{module} failed with exit code {result.returncode}")


def build(cell_km: float) -> None:
    km = f"{cell_km:g}"
    started = time.time()
    run("scripts.aggregate_grid", "--cell-km", km)
    run("scripts.build_pairs", "--cell-km", km)
    run("ml.training.train_harmonization", "--cell-km", km, "--version", version_name(cell_km), "--no-register")
    run("ml.evaluation.evaluate_model", "--version", version_name(cell_km), "--no-docs")
    timing = {"cell_km": cell_km, "minutes": round((time.time() - started) / 60, 1)}
    (config.ARTIFACTS_DIR / version_name(cell_km) / "resolution_run.json").write_text(json.dumps(timing), encoding="utf-8")


def collect(cell_km: float, operational: float) -> dict | None:
    version = active_version() if cell_km == operational else version_name(cell_km)
    directory = config.ARTIFACTS_DIR / version
    if not (directory / "metrics.json").exists():
        return None
    metrics = json.loads((directory / "metrics.json").read_text(encoding="utf-8"))
    tag = config.grid_tag(cell_km)
    cells = json.loads((config.GRID_DIR / tag / "aggregation_report.json").read_text(encoding="utf-8"))["cells"]
    pairs = json.loads((config.FEATURES_DIR / tag / "pairs_report.json").read_text(encoding="utf-8"))
    test_years = set(config.years_between(config.TEST_YEARS))
    test_pairs = [p for p in pairs if p["year"] in test_years]
    province = metrics["aggregated"]["test"]["province_day"]
    country = metrics["aggregated"]["test"]["country_day"]
    return {
        "cell_km": cell_km,
        "version": version,
        "operational": cell_km == operational,
        "cells": cells,
        "test_cell_days": sum(p["informed_cell_days"] for p in test_pairs),
        "modis_in_cell": sum(p["with_modis_in_cell"] for p in test_pairs),
        "viirs_share": sum(p["viirs_detections_in_informed"] for p in test_pairs)
        / sum(p["viirs_detections"] for p in test_pairs),
        "cell_day_count": metrics["cell_day"]["test"]["count"]["lightgbm"],
        "province_day_count": province["count"],
        "province_day_frp": province["frp"],
        "country_day_count": country["count"],
        "high_activity": metrics["high_activity"]["test"]["lightgbm"],
    }


def write_markdown(rows: list[dict]) -> None:
    test = config.TEST_YEARS
    period = str(test[0]) if test[0] == test[1] else f"{test[0]}-{test[1]}"
    lines = [
        "# Grid resolution comparison",
        "",
        f"Generated by `ml/evaluation/compare_resolutions.py` on "
        f"{datetime.now(timezone.utc).isoformat(timespec='seconds')}. Do not edit by hand.",
        "",
        f"Same data, same split and same training settings at every cell size; independent test period {period}. "
        "Reference: VIIRS S-NPP. The model of the operational grid is the one used by the application; the others "
        "are trained only for this comparison.",
        "",
        "## Size of the problem",
        "",
        "A cell-day is MODIS-informed when MODIS has a detection in the cell or in one of its eight neighbours "
        "within one day, so the neighbourhood grows with the cell: 3 km across at 1 km, 15 km at 5 km, 30 km at "
        "10 km. VIIRS detections outside informed cell-days are only covered by the background rate.",
        "",
        f"Counts for the test period ({period}):",
        "",
        "| Cell size | Grid cells | Informed cell-days | With MODIS in the cell | VIIRS detections inside informed cell-days |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        mark = " (operational)" if r["operational"] else ""
        lines.append(
            f"| {r['cell_km']:g} km{mark} | {r['cells']:,} | {r['test_cell_days']:,} | "
            f"{100 * r['modis_in_cell'] / r['test_cell_days']:.1f} % | {100 * r['viirs_share']:.1f} % |"
        )

    def table(title: str, key: str, note: str) -> None:
        lines.extend(
            [
                "",
                f"## {title}",
                "",
                note,
                "",
                "| Cell size | Method | MAE | RMSE | R² | Bias % | Spearman |",
                "|---|---|---|---|---|---|---|",
            ]
        )
        for r in rows:
            block = r[key]
            methods = block if "mae" not in block else {"lightgbm": block}
            for name in ("modis_raw", "linear", "lightgbm"):
                if name not in methods:
                    continue
                m = methods[name]
                label = {"modis_raw": "Original MODIS", "linear": "Linear regression", "lightgbm": "LightGBM"}[name]
                lines.append(
                    f"| {r['cell_km']:g} km | {label} | {m['mae']:,.3f} | {m['rmse']:,.3f} | {m['r2']:.3f} | "
                    f"{m['bias_pct']:+.1f} | {m['spearman']:.3f} |"
                )

    table("Detection count by province and day", "province_day_count",
          "The target is the same at every resolution: VIIRS detections per province and day.")
    table("FRP by province and day (MW)", "province_day_frp",
          "VIIRS FRP per province and day.")
    table("Detection count, national daily totals", "country_day_count",
          "VIIRS detections per day over the whole country.")
    table("Detection count at cell-day level", "cell_day_count",
          "Here the target itself changes with the cell size, so the rows are not directly comparable: "
          "larger cells average out more of the sensor-to-sensor noise.")

    lines.extend(
        [
            "",
            "## High-activity days by province",
            "",
            "Thresholds are the 90th percentile of each province's daily VIIRS HFAI in the training years, "
            "computed separately at each resolution.",
            "",
            "| Cell size | Observed | Flagged | Precision | Recall | F1 |",
            "|---|---|---|---|---|---|",
        ]
    )
    for r in rows:
        h = r["high_activity"]
        lines.append(
            f"| {r['cell_km']:g} km | {h['observed_high']} | {h['predicted_high']} | {h['precision']:.3f} | "
            f"{h['recall']:.3f} | {h['f1']:.3f} |"
        )

    def lgbm(r: dict) -> dict:
        return r["province_day_count"]["lightgbm"]

    best_rmse = min(rows, key=lambda r: lgbm(r)["rmse"])
    best_bias = min(rows, key=lambda r: abs(lgbm(r)["bias_pct"]))
    lines.extend(["", "## Summary", "", "LightGBM plus background, detection count by province and day:", ""])
    for r in rows:
        m = lgbm(r)
        lines.append(f"- {r['cell_km']:g} km: RMSE {m['rmse']:,.1f}, R² {m['r2']:.3f}, bias {m['bias_pct']:+.1f} %.")
    lines.extend(
        [
            "",
            f"Lowest RMSE: {best_rmse['cell_km']:g} km. Smallest absolute bias: {best_bias['cell_km']:g} km.",
            "",
        ]
    )
    (config.DOCS_DIR / "resolution_comparison.md").write_text("\n".join(lines), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cell-km", nargs="+", type=float, default=[1.0, 5.0, 10.0])
    parser.add_argument("--collect-only", action="store_true", help="only rebuild the report from existing runs")
    args = parser.parse_args(argv)

    operational = float(config.CELL_KM)
    sizes = sorted(set(args.cell_km) | {operational})
    if not args.collect_only:
        for cell_km in sizes:
            if cell_km != operational:
                print(f"\n=== {cell_km:g} km ===", flush=True)
                build(cell_km)

    every = sorted({1.0, 2.0, 2.5, 5.0, 10.0, 20.0, 25.0} | set(sizes))
    rows = [row for row in (collect(km, operational) for km in every) if row]
    if len(rows) < 2:
        print("Nothing to compare yet.")
        return 1
    write_markdown(rows)
    print(f"Wrote {config.DOCS_DIR / 'resolution_comparison.md'} ({', '.join(f'{r['cell_km']:g} km' for r in rows)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
